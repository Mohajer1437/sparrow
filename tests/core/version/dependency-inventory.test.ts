import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import {
  buildDependencyInventory,
  categorizeDependency,
  extractFrameworkVersionInfo,
  normalizeTechnologyName,
} from '../../../src/core/version/dependency-inventory';
import {
  parsePackageLock,
  parsePnpmLock,
  parseYarnLock,
} from '../../../src/core/version/lockfile-parser';

describe('Dependency Inventory & Lockfile Awareness', () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'dep-inv-test-'));
  });

  afterEach(() => {
    fs.rmSync(tempDir, { recursive: true, force: true });
  });

  describe('categorizeDependency & normalizeTechnologyName', () => {
    it('categorizes dependencies into appropriate domains', () => {
      expect(categorizeDependency('next')).toBe('framework');
      expect(categorizeDependency('@nestjs/core')).toBe('framework');
      expect(categorizeDependency('@prisma/client')).toBe('orm');
      expect(categorizeDependency('prisma')).toBe('orm');
      expect(categorizeDependency('pg')).toBe('database');
      expect(categorizeDependency('jest')).toBe('testing');
      expect(categorizeDependency('@playwright/test')).toBe('testing');
      expect(categorizeDependency('typescript')).toBe('runtime');
      expect(categorizeDependency('tailwindcss')).toBe('ui');
      expect(categorizeDependency('eslint')).toBe('lint');
      expect(categorizeDependency('webpack')).toBe('build');
      expect(categorizeDependency('lodash')).toBe('utility');
    });

    it('normalizes technology identifiers consistently', () => {
      expect(normalizeTechnologyName('next')).toBe('nextjs');
      expect(normalizeTechnologyName('@nestjs/core')).toBe('nestjs');
      expect(normalizeTechnologyName('@nestjs/common')).toBe('nestjs');
      expect(normalizeTechnologyName('@prisma/client')).toBe('prisma');
      expect(normalizeTechnologyName('prisma')).toBe('prisma');
      expect(normalizeTechnologyName('@playwright/test')).toBe('playwright');
      expect(normalizeTechnologyName('typescript')).toBe('typescript');
    });
  });

  describe('Lockfile parsers', () => {
    it('parses package-lock.json v3 format', () => {
      const lockJson = JSON.stringify({
        name: 'test-app',
        lockfileVersion: 3,
        packages: {
          '': { name: 'test-app' },
          'node_modules/next': { version: '14.2.35' },
          'node_modules/@prisma/client': { version: '7.2.1' },
        },
      });

      const parsed = parsePackageLock(lockJson);
      expect(parsed.get('next')).toBe('14.2.35');
      expect(parsed.get('@prisma/client')).toBe('7.2.1');
    });

    it('parses package-lock.json v1 format', () => {
      const lockJson = JSON.stringify({
        name: 'test-app',
        lockfileVersion: 1,
        dependencies: {
          next: { version: '14.1.0' },
          prisma: { version: '6.4.0' },
        },
      });

      const parsed = parsePackageLock(lockJson);
      expect(parsed.get('next')).toBe('14.1.0');
      expect(parsed.get('prisma')).toBe('6.4.0');
    });

    it('parses yarn.lock v1 format', () => {
      const yarnLock = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT.
"next@^14.2.0", next@14.2.35:
  version "14.2.35"
  resolved "https://registry.yarnpkg.com/next/-/next-14.2.35.tgz"

"@nestjs/core@^10.0.0":
  version "10.3.2"
`;

      const parsed = parseYarnLock(yarnLock);
      expect(parsed.get('next')).toBe('14.2.35');
      expect(parsed.get('@nestjs/core')).toBe('10.3.2');
    });

    it('parses pnpm-lock.yaml format', () => {
      const pnpmLock = `
lockfileVersion: '6.0'

packages:
  /next@14.2.35(react-dom@18.3.0)(react@18.3.0):
    resolution: {integrity: sha512-xxx}
  /@nestjs/core@10.3.0:
    resolution: {integrity: sha512-yyy}
`;

      const parsed = parsePnpmLock(pnpmLock);
      expect(parsed.get('next')).toBe('14.2.35');
      expect(parsed.get('@nestjs/core')).toBe('10.3.0');
    });
  });

  describe('buildDependencyInventory', () => {
    it('detects declared vs resolved versions when lockfile exists', () => {
      fs.writeFileSync(
        path.join(tempDir, 'package.json'),
        JSON.stringify({
          dependencies: {
            next: '^14.2.0',
            prisma: '^7.0.0',
          },
          devDependencies: {
            typescript: '^5.3.0',
          },
        }),
      );

      fs.writeFileSync(
        path.join(tempDir, 'package-lock.json'),
        JSON.stringify({
          name: 'sample',
          lockfileVersion: 3,
          packages: {
            'node_modules/next': { version: '14.2.35' },
            'node_modules/prisma': { version: '7.2.1' },
            'node_modules/typescript': { version: '5.3.3' },
          },
        }),
      );

      const deps = buildDependencyInventory(tempDir);
      expect(deps.length).toBe(3);

      const nextDep = deps.find(d => d.name === 'next');
      expect(nextDep).toBeDefined();
      expect(nextDep?.declaredVersion).toBe('^14.2.0');
      expect(nextDep?.resolvedVersion).toBe('14.2.35');
      expect(nextDep?.versionSource).toBe('lockfile');
      expect(nextDep?.category).toBe('framework');
      expect(nextDep?.normalizedName).toBe('nextjs');

      const prismaDep = deps.find(d => d.name === 'prisma');
      expect(prismaDep).toBeDefined();
      expect(prismaDep?.declaredVersion).toBe('^7.0.0');
      expect(prismaDep?.resolvedVersion).toBe('7.2.1');
      expect(prismaDep?.versionSource).toBe('lockfile');
      expect(prismaDep?.category).toBe('orm');

      const tsDep = deps.find(d => d.name === 'typescript');
      expect(tsDep).toBeDefined();
      expect(tsDep?.dependencyType).toBe('devDependencies');
      expect(tsDep?.resolvedVersion).toBe('5.3.3');
    });

    it('falls back to manifest version when lockfile is absent', () => {
      fs.writeFileSync(
        path.join(tempDir, 'package.json'),
        JSON.stringify({
          dependencies: {
            next: '^15.0.0',
          },
        }),
      );

      const deps = buildDependencyInventory(tempDir);
      expect(deps.length).toBe(1);
      expect(deps[0].declaredVersion).toBe('^15.0.0');
      expect(deps[0].resolvedVersion).toBeUndefined();
      expect(deps[0].versionSource).toBe('manifest');
    });

    it('handles missing package.json safely returning empty inventory', () => {
      const deps = buildDependencyInventory(tempDir);
      expect(deps).toEqual([]);
    });
  });

  describe('extractFrameworkVersionInfo', () => {
    it('extracts framework versions accurately for project profile', () => {
      const deps = [
        {
          name: 'next',
          normalizedName: 'nextjs',
          category: 'framework' as const,
          declaredVersion: '^14.2.0',
          resolvedVersion: '14.2.35',
          versionSource: 'lockfile' as const,
          dependencyType: 'dependencies' as const,
        },
      ];

      const fwInfo = extractFrameworkVersionInfo(['nextjs', 'nestjs'], deps);
      expect(fwInfo.length).toBe(2);

      const nextFw = fwInfo.find(f => f.name === 'nextjs');
      expect(nextFw?.declaredVersion).toBe('^14.2.0');
      expect(nextFw?.resolvedVersion).toBe('14.2.35');
      expect(nextFw?.versionSource).toBe('lockfile');

      const nestFw = fwInfo.find(f => f.name === 'nestjs');
      expect(nestFw?.resolvedVersion).toBeUndefined();
      expect(nestFw?.versionSource).toBe('unknown');
    });
  });
});
